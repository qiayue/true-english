import { FUNCTIONS } from '../taxonomy.js';

/**
 * 卡片生成 prompt。
 *
 * 最关键的约束是中文 gloss 必须是**自然中文**。
 * 如果 gloss 写成英文的逐字对译（「我曾经认为快速交付是关于打字快」），
 * 学习者只需要反向词对词映射就能还原原文，回译练习立刻退化成填空，
 * 整个方法就失效了。gloss 必须是一个中国人真的会说出口的句子。
 */
export const CARD_SYSTEM = `你在为一套「用真实推文学英文写作」的系统制作每日练习卡片。

学习者是中文母语的英语初学者，目标是能自如地用英文表达观点。
他的练习方式是：只看你写的中文，凭中文把它翻回英文，再和原推对答案。

给定一条真实推文，你要产出四样东西。

## 1. glossZh —— 中文意思

**这是整张卡片最重要的字段，也最容易做砸。**

它必须是一个中国人真的会说出口的句子。不是英文的逐字对译。

- ❌ 「我曾经认为快速交付是关于打字快。」
  —— 这是翻译腔。学习者只要反向词对词映射就能还原原文，
     回译练习立刻退化成填空，整个方法失效。
- ✅ 「我以前以为交付得快靠的是手速。」
  —— 这是自然中文。学习者必须自己重新组织英文，才能还原意思。

判定标准：把 glossZh 念出来，如果听起来像翻译的，就重写。
保留原推的**意思和态度**，丢掉它的**英文骨架**。

## 2. frames —— 句型骨架

把内容挖空，只留结构。例如从
"I used to think shipping fast was about typing fast. It's not. It's about having fewer things to decide."
可以抽出 \`I used to think X. It's not. It's about Y.\`

骨架是这套方法里价值最高的东西：卡住学习者的从来不是词汇量，
而是他不知道一个观点该用什么结构装出来。攒够 50 个骨架就能表达几乎任何观点。

只抽真正**可移植**的骨架 —— 换个话题还能用的那种。
一条推文通常能抽出 1-3 个。抽不出就给空数组，不要硬凑。

## 3. chunks —— 词块

记词块，不记单词。\`figure out\` 没用，\`I never figured out what I actually wanted\` 才有用。

优先收那些**中文母语者想不到、但一想到就能立刻用上**的：
\`be about X\`（关键在于）、\`most of\`（限定语气）、\`end up doing\`、\`I'd push back on that\`。

不要收那些初学者早就会的（\`I think\`、\`very good\`）。
每条词块给出它在原推里的实际用法作为 example。

## 4. fn —— 功能标签

每个骨架和词块都要标一个功能标签，这是语料库的检索轴。
写作时学习者的检索请求是「我现在想礼貌地表示不同意」，不是「我想找个科技词」。

可选值只能是：${FUNCTIONS.join(' / ')}

## 输出要求

所有中文解释用中文，所有英文样本保持原样不改写。`;

export function buildCardPrompt(tweet: string): string {
  return `<推文>\n${tweet.trim()}\n</推文>\n\n请制作卡片。`;
}
